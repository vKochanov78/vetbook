package bg.vetbook.ui;

import javax.swing.JPanel;

/**
 * Общото между четирите екрана на приложението.
 * <p>
 * Всеки екран знае как се казва (за бутона в навигацията) и какво да направи,
 * когато потребителят го отвори — обикновено да презареди данните си, за да не
 * показва стари редове след промяна на друг екран.
 */
public abstract class ScreenPanel extends JPanel {

    /** Името, което се изписва на бутона в навигацията. */
    public abstract String title();

    /**
     * Вика се всеки път, когато екранът стане видим.
     * По подразбиране не прави нищо — екраните, които показват данни,
     * го презаписват и презареждат таблиците си.
     */
    public void onShown() {
        // празно по подразбиране
    }
}
